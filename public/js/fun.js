const ISPS = ['ksc', 'loxinfo', 'cscoms', 'inet', 'asianet', 'samart', 'tttmaxnet', 'jasmine'];
export function fakeHost(id = '') {
  let h = 0;
  for (const c of id) h = (h * 33 + c.charCodeAt(0)) >>> 0;
  const isp = ISPS[h % ISPS.length];
  return `~pirch@ppp-${(h % 200) + 20}-${(h >>> 8) % 250}.dialup-56k.${isp}.th`;
}

